# Arithmetic operators - basically a calculator.

print(1 + 1)    # 2   add
print(2 - 1)    # 1   subtract
print(2 * 2)    # 4   multiply
print(4 / 2)    # 2.0 divide (always gives a decimal)
print(4 % 3)    # 1   remainder
print(4 ** 2)   # 16  power
print(5 // 2)   # 2   floor division (chops off the decimal)

# Shortcut: += adds and saves in one go
age = 8
age += 1
print(age)  # 9
