# Bitwise operators work on the 0s and 1s behind a number.
# You won't need these much as a beginner - just good to know they exist.

a = 5   # binary 101
b = 3   # binary 011

print(a & b)   # AND  -> 1
print(a | b)   # OR   -> 7
print(a ^ b)   # XOR  -> 6
print(a << 1)  # shift left  -> 10
print(a >> 1)  # shift right -> 2
