# An expression is any bit of code that gives back a value.
# A statement is a full instruction, like "assign this" or "print that".

1 + 1          # expression -> 2
"Roger"        # expression -> "Roger"

name = "Roger"  # statement (an assignment)
print(name)     # statement

# You can put two statements on one line with a semicolon, but honestly it's rarely done
a = 1; print(a)
