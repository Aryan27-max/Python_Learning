# Python has three number types: int, float, complex

whole = 10        # int
decimal = 3.14    # float
fancy = 2 + 3j    # complex (rarely used, just so you know)

print(type(whole), type(decimal), type(fancy))

# A few handy number functions
print(abs(-5))          # 5
print(round(3.567, 2))  # 3.57
print(round(4.5))       # 4  (rounds to the nearest even number, a bit quirky!)
