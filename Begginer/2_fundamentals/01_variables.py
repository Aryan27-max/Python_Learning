# Variables are like labelled boxes - you put a value in and give it a name.

name = "Roger"
age = 8

print(name)
print(age)

# You can change what's in the box anytime
age = 9
print("Next year Roger will be", age)

# Rules: names can have letters, numbers and _ but can't start with a number.
# my_name is fine, 1name is not.
